"""Generate a complete Lean proof for an externally fixed nonnegative n.

Usage: python generate.py n
Example: python generate.py 3
Then check: lake env lean ConZFCIn/Instances/N3.lean

The generator is outside the trusted kernel. The generated theorem has only
the EM parameter; its proof constructs the model, intervals, and strict chain.
"""
from pathlib import Path
import argparse


def proof(n: int) -> str:
    lines = [
        "import ConZFCIn.Model.Soundness",
        "import ConZFCIn.Model.Interval",
        "import ConZFCIn.Universe.Coherence",
        "",
        f"/-! For externally fixed n = {n}. Generated by generate.py; verify with the Lean kernel. -/",
        "namespace ConZFCIn",
        "open PSet PSet.Multi",
        "",
        f"theorem con_ZFCIn_{n} (em : ∀ p : Prop, p ∨ ¬p) : PSet.Con (ZFCIn {n}) := by",
    ]
    if n == 0:
        lines += [
            "  exact con_ZFCIn_seeded PSet.empty.{0} em (n := 0) trivial",
        ]
    else:
        for i in range(n):
            lines += [f"  let k{i} : PSet.{{{n}}} := PSet.Multi.K.{{{i},{n}}}"]
        lines += [f"  let t : PSet.{{{n}}} := k{n-1}"]
        for i in range(n-1):
            lines += [
                f"  have step{i} : k{i} ∈ k{i+1} := PSet.Multi.height_strict.{{{i},{n}}}",
            ]
        for i in reversed(range(n-1)):
            expression = f"step{i}" if i == n-2 else (
                f"PSet.Multi.isOrd_K.{{{n-1},{n}}}.trans k{i+1} top{i+1} k{i} step{i}"
            )
            lines += [f"  have top{i} : k{i} ∈ t := {expression}"]
        for i in range(n):
            expression = "self_mem_succ t" if i == n-1 else f"mem_succ_of_mem top{i}"
            lines += [f"  have le{i} : k{i} ∈ succ t := {expression}"]
        for i in range(n):
            lower = "PSet.empty.{0}" if i == 0 else f"PSet.Multi.K.{{{i-1},0}}"
            lines += [
                f"  obtain ⟨r{i}, hr{i}, below{i}, above{i}, hi{i}⟩ :=",
                f"    PSet.Multi.inacc_interval_seeded.{{{i},{n-1}}} t em",
                f"      PSet.Multi.isOrd_K.{{{n-1},{n}}} le{i} ({lower})",
            ]
            if i > 0:
                lines += [
                    f"  have lower{i} : k{i-1} ∈ r{i} :=",
                    "    (mem_congr_left",
                    f"      ((PSet.Multi.lift_congr.{{{i},{n}}} PSet.Multi.isOrd_K.{{{i-1},0}}.rank_equiv).trans",
                    f"        PSet.Multi.lift_K.{{{i-1},0,{n}}})).1 below{i}",
                    f"  have order{i} : r{i-1} ∈ r{i} :=",
                    f"    PSet.Multi.mem_of_interval_separation hi{i}.1 above{i-1} lower{i}",
                ]
        nested = "trivial"
        for i in reversed(range(1, n)):
            nested = f"⟨r{i}, hr{i}, hi{i}, order{i}, {nested}⟩"
        nested = f"⟨r0, hr0, hi0, {nested}⟩"
        lines += [
            f"  have chain : InaccChain (PSet.Multi.L t) {n} := {nested}",
            "  exact con_ZFCIn_seeded t em chain",
        ]
    lines += ["", "end ConZFCIn", "", f"#print axioms ConZFCIn.con_ZFCIn_{n}", ""]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("n", type=int, help="an externally fixed nonnegative integer")
    args = parser.parse_args()
    if args.n < 0:
        parser.error("n must be nonnegative")
    root = Path(__file__).resolve().parent
    target = root / "ConZFCIn" / "Instances" / f"N{args.n}.lean"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(proof(args.n), encoding="utf-8")
    print(target.relative_to(root).as_posix())


if __name__ == "__main__":
    main()
